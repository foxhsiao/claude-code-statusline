#!/usr/bin/env bash
# Checks that must pass before the mod is pushed: plugin validation, unit tests, type check.
# The pre-push hook (scripts/hooks/pre-push) runs this; run it by hand too.
#
#   TSC=/path/to/tsc   the TypeScript compiler for the type check (else node_modules/.bin/tsc, else `tsc` on PATH)
#   CHECK_STRICT=1     a missing tool fails the check instead of skipping that step
set -u
cd "$(dirname "$0")/.." || exit 1

MOD=mods/statusline-capsule
BASELINE=scripts/tsc-baseline.txt
STRICT=${CHECK_STRICT:-0}

if [ -t 1 ]; then G=$'\033[32m'; R=$'\033[31m'; Y=$'\033[33m'; N=$'\033[0m'; else G=; R=; Y=; N=; fi
failed=0
ok()   { printf '%s✔%s %s\n' "$G" "$N" "$1"; }
bad()  { printf '%s✘%s %s\n' "$R" "$N" "$1"; failed=1; }
skip() {
  if [ "$STRICT" = 1 ]; then bad "$1（CHECK_STRICT=1：缺工具視為失敗）"
  else printf '%s–%s %s\n' "$Y" "$N" "$1"; fi
}
indent() { sed 's/^/    /'; }

if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
  printf '%s注意：工作區有未 commit 的變動，檢查的是工作區，不是要推送的 commit。%s\n' "$Y" "$N"
fi

# 1. the plugin has to load: this is what catches a hook the host would refuse (0.5.0 shipped without it)
if command -v claude >/dev/null 2>&1; then
  out=$(claude plugin validate "$MOD" 2>&1); rc=$?
  if [ $rc -eq 0 ] && printf '%s' "$out" | grep -q 'Validation passed'; then
    ok "plugin validate"
  else
    bad "plugin validate"; printf '%s\n' "$out" | tail -15 | indent
  fi
else
  skip "plugin validate：找不到 claude 指令"
fi

# 2. unit tests (*.test.ts under the mod), run by the host's own runner
if command -v claude >/dev/null 2>&1; then
  out=$(claude plugin test "$MOD" 2>&1); rc=$?
  summary=$(printf '%s\n' "$out" | grep -E '^ *[0-9]+ (pass|fail)' | tr -s ' ' | tr '\n' ' ')
  if [ $rc -eq 0 ]; then
    ok "單元測試 ($summary)"
  else
    bad "單元測試 ($summary)"; printf '%s\n' "$out" | grep -E '\(fail\)|error|Error' | head -15 | indent
  fi
else
  skip "單元測試：找不到 claude 指令"
fi

# 3. type check: the mod has known errors (the baseline); only a new one fails
tsc=${TSC:-}
if [ -z "$tsc" ]; then
  # the version the repo pins first, a global one only as a fallback
  if [ -x node_modules/.bin/tsc ]; then tsc=node_modules/.bin/tsc
  elif command -v tsc >/dev/null 2>&1; then tsc=$(command -v tsc); fi
fi
if [ -z "$tsc" ]; then
  skip "型別檢查：找不到 tsc（設 TSC=/path/to/tsc，或在 repo 根目錄 npm i -D typescript）"
elif [ ! -f "$MOD/.claude-plugin/types/claude-code/index.d.ts" ]; then
  # that folder is generated by Claude Code and ignored by git; without it every import is an error
  skip "型別檢查：缺少 $MOD/.claude-plugin/types（由 Claude Code 產生，用 claude --plugin-dir 開一次即可）"
else
  out=$("$tsc" --noEmit -p "$MOD" 2>&1); rc=$?
  # drop line/column so a shifted line is not a new error; keep duplicates so a repeat of a known message counts
  cur=$(printf '%s\n' "$out" | grep 'error TS' | sed -E 's/\([0-9]+,[0-9]+\)//' | sort)
  base=$(grep -v -e '^#' -e '^$' "$BASELINE" 2>/dev/null | sort)
  if [ $rc -ne 0 ] && [ -z "$cur" ]; then
    bad "型別檢查：tsc 沒有正常執行"; printf '%s\n' "$out" | tail -10 | indent
  else
    new=$(comm -23 <(printf '%s\n' "$cur") <(printf '%s\n' "$base") | grep -v '^$')
    gone=$(comm -13 <(printf '%s\n' "$cur") <(printf '%s\n' "$base") | grep -v '^$')
    n=$(printf '%s\n' "$cur" | grep -c 'error TS')
    if [ -z "$new" ]; then
      ok "型別檢查（$n 個既有錯誤，沒有新增）"
    else
      bad "型別檢查：新增 $(printf '%s\n' "$new" | grep -c .) 個錯誤"; printf '%s\n' "$new" | indent
    fi
    if [ -n "$gone" ]; then
      printf '    已不再出現，可從 %s 移除：\n' "$BASELINE"; printf '%s\n' "$gone" | indent
    fi
  fi
fi

if [ $failed -ne 0 ]; then
  printf '\n%s檢查未通過，push 已被擋下。確定要略過時用 git push --no-verify。%s\n' "$R" "$N"
  exit 1
fi
printf '\n%s全部通過。%s\n' "$G" "$N"
